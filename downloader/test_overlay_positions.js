const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require(process.env.STUDIO_JSDOM||'./.test-tools/node_modules/jsdom');
const platforms=['threads-download-btn-container','youtube-shorts-download-btn-container','takoh-video-overlay-btn','takoh-image-overlay-btn'];
for(const platform of platforms) {
 const dom=new JSDOM('<article><div id="host"><video></video><button id="native">Close</button><div class="threads-download-btn-container"><button class="threads-download-btn"><span>Video</span></button></div></div></article>',{url:'https://example.com/',runScripts:'outside-only'});
 const w=dom.window;
 w.document.querySelector('.threads-download-btn-container').className=platform;
 w.chrome={runtime:{getURL:x=>x,onMessage:{addListener(){}}},storage:{local:{get:(k,cb)=>cb({})},onChanged:{addListener(){}}}};
 const d=w.document,host=d.querySelector('#host'),video=d.querySelector('video'),control=d.querySelector('.'+platform);
 let mediaRect={left:100,top:100,right:500,bottom:500,width:400,height:400};
 let origin={left:20,top:30,right:600,bottom:600,width:580,height:570};
 host.getBoundingClientRect=()=>origin;
 video.getBoundingClientRect=()=>mediaRect;
 d.querySelector('#native').getBoundingClientRect=()=>({left:100,top:100,right:220,bottom:142,width:120,height:42});
 Object.defineProperty(control,'offsetParent',{get:()=>host});
 Object.defineProperty(control,'offsetWidth',{get:()=>control.classList.contains('takoh-compact-controls')?36:110});
 Object.defineProperty(control,'offsetHeight',{value:34});
 w.eval(fs.readFileSync('content-studio.js','utf8'));
 w.eval(fs.readFileSync('content-core.js','utf8'));
 const core=w.TAKCore;
 core.anchorMediaControls(control,video);
 assert.equal(control.querySelectorAll('.takoh-collect-reference').length,1);
 core.updateMediaControlPositions();
 assert.equal(control.style.left,'362px',platform+' must avoid native top-left control');
 assert.equal(control.style.top,'78px',platform+' must follow actual video within larger host');
 mediaRect={left:100,top:-60,right:280,bottom:220,width:180,height:280};
 core.updateMediaControlPositions();
 assert.ok(control.classList.contains('takoh-compact-controls'),platform+' narrow media must compact');
 assert.equal(control.style.top,'-22px',platform+' visible viewport edge must clamp');
 mediaRect={left:-500,top:100,right:-100,bottom:500,width:400,height:400};
 core.updateMediaControlPositions();
 assert.equal(control.style.display,'none',platform+' offscreen media must hide');
 mediaRect={left:100,top:100,right:500,bottom:500,width:400,height:400};
 core.anchorMediaControls(control,video,true);
 core.updateMediaControlPositions();
 assert.equal(control.style.position,'fixed');
 assert.equal(control.style.top,'108px');
 video.remove();core.updateMediaControlPositions();
 assert.equal(control.style.display,'none',platform+' removed media must not leave active overlay');
 dom.window.close();
}
console.log('Overlay layout passed for 4 overlay families: media origin, native controls, compact, viewport, portal, removal');
